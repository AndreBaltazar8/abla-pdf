#!/usr/bin/env python3
# Writes src/encoding_data.ab: the widths of the standard 14 fonts over
# WinAnsiEncoding, the predefined simple-font encodings as code point tables,
# and the Adobe Glyph List. Run with reportlab and fonttools available:
#   nix-shell -p 'python3.withPackages(p: [p.reportlab p.fonttools])' \
#     --run 'python3 tools/gen-encoding-data.py > src/encoding_data.ab'
from fontTools import agl
from reportlab.pdfbase import _fontdata as fd

def uni(name):
    if name is None or name == '.notdef':
        return 0
    if name in agl.AGL2UV:
        v = agl.AGL2UV[name]
        return v if isinstance(v, int) else v[0]
    s = agl.toUnicode(name)
    return ord(s[0]) if s else 0

fonts = ['Helvetica', 'Helvetica-Bold', 'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic']
win = fd.encodings['WinAnsiEncoding']
def rows(values):
    lines = []
    for i in range(0, len(values), 16):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + 16]))
    return ',\n'.join(lines)

print('// Generated by tools/gen-encoding-data.py. Do not edit.')
print()
for font in fonts:
    w = fd.widthsByFontGlyph[font]
    values = [w.get(win[c], 0) if win[c] else 0 for c in range(256)]
    print('val PDF_WIDTHS_%s = [\n%s\n]\n' % (font.upper().replace('-', '_'), rows(values)))

def table(name, values):
    print('val %s = [\n%s\n]\n' % (name, rows(values)))

cp1252 = [0] * 256
for c in range(256):
    try:
        cp1252[c] = ord(bytes([c]).decode('cp1252'))
    except UnicodeDecodeError:
        cp1252[c] = 0x2022 if c >= 0x80 else 0
    if c < 32:
        cp1252[c] = 0
cp1252[0x7f] = 0x2022
cp1252[0xa0] = 0x20
cp1252[0xad] = 0x2d
table('PDF_ENCODING_WINANSI', cp1252)

mac = [0] * 256
for c in range(32, 256):
    mac[c] = ord(bytes([c]).decode('mac_roman'))
mac[0x7f] = 0
mac[0xca] = 0x20
table('PDF_ENCODING_MACROMAN', mac)
table('PDF_ENCODING_STANDARD', [uni(fd.encodings['StandardEncoding'][c]) for c in range(256)])
table('PDF_ENCODING_SYMBOL', [uni(fd.encodings['SymbolEncoding'][c]) for c in range(256)])

doc = [0] * 256
for c in list(range(9, 11)) + [13] + list(range(32, 127)) + list(range(0xa1, 0x100)):
    doc[c] = c
doc[0xa0] = 0x20ac
for c, v in zip(range(0x18, 0x20), [0x2d8, 0x2c7, 0x2c6, 0x2d9, 0x2dd, 0x2db, 0x2da, 0x2dc]):
    doc[c] = v
for c, v in zip(range(0x80, 0x9f), [0x2022, 0x2020, 0x2021, 0x2026, 0x2014, 0x2013, 0x192, 0x2044,
        0x2039, 0x203a, 0x2212, 0x2030, 0x201e, 0x201c, 0x201d, 0x2018, 0x2019, 0x201a, 0x2122,
        0xfb01, 0xfb02, 0x141, 0x152, 0x160, 0x178, 0x17d, 0x131, 0x142, 0x153, 0x161, 0x17e]):
    doc[c] = v
table('PDF_ENCODING_PDFDOC', doc)

entries = sorted((n, v) for n, v in agl.AGL2UV.items() if isinstance(v, int))
text = ';'.join('%s:%x' % e for e in entries)
print('val PDF_GLYPH_LIST = "%s"' % text)
